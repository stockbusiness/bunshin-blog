-- 案件の事実を確かめ直した時刻（TASKS D-13-schema、OPEN_QUESTIONS Q-022）。
--
-- ## なぜ要るのか
--
-- CONTENT_PLANNING 8.2 が「`offer.facts.updatedAt` が90日より古い場合は、
-- 照合が一致しても `WARNING` とする」と定めている。E-12 で実装したが、
-- **この値を書く経路がどこにも無い。**
--
-- E-12 は「分からなければ古い扱い」にした（**測っていないことを
-- 「問題なし」に化けさせない**）ため、**いま全ての収益記事が `WARNING`**
-- になっている。
--
-- ## なぜ `updated_at` で代用できないのか
--
-- `affiliate_offers.updated_at` は**行のどの列を変えても更新される。**
-- 状態を `ACTIVE` にしただけ、報酬額を直しただけで
-- 「事実を確かめ直した」ことになってしまう。
--
-- 90日判定が見たいのは「**報酬・条件・キャンペーンの内容を確かめ直したのは
-- いつか**」であって、行を触った時刻ではない。
--
-- ## なぜ jsonb の中ではなく列なのか
--
-- 仕様の記述は `offer.facts.updatedAt` だが、**jsonb の中に書く規約は
-- 書き忘れを防げない**（制約を置けない）。列にすれば、
-- **`facts` を実際に変えた経路だけが触る**ものとして扱える（D-13）。
--
-- ## 既定値を入れない・既存行を埋めない
--
-- **NULL のままにする。** ここで `now()` を入れると、
-- **一度も確かめていない案件が「今日確かめた」ことになる。**
-- 90日判定は黙って通り、古い価格が「確認済み」として公開される。
--
-- 「いつ確かめたか分からない」は「新しい」ではない。E-12 が
-- 「無ければ古い扱い」にしたのと同じ判断で、**鳴りっぱなしのほうが安全側。**
-- 鳴り止むのは、D-13 の経路で実際に確かめ直したときだけ。

-- AlterTable
ALTER TABLE "affiliate_offers" ADD COLUMN     "facts_updated_at" TIMESTAMPTZ(6);
