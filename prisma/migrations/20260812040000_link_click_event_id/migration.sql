-- 再送で二重に数えないための鍵（D-12）。
--
-- ## なぜ要るか
--
-- リダイレクタを各ブログのドメインへ移すと、クリックは
-- **WordPress → Bunshin の受信API** という送信になる（Q-001 の再決定）。
-- 送信に失敗したらWordPress側で保持し、次回まとめて送る。
--
-- **応答だけが失われた場合、同じクリックが2回届く。** 受信APIは
-- 「保存できたか」を送信元へ返せているとは限らないので、
-- **送信元が回数を正しく制御することはできない。**
--
-- 送信元がクリックの瞬間に付ける識別子を鍵にして、2回目を落とす。
--
-- ## なぜアプリ層だけに置かないか
--
-- 「入っているか調べてから入れる」は、同じ電文が同時に2回届いたときに
-- **両方とも「まだ無い」と判定して通る。** 受信APIは外から叩かれる入口で、
-- 同時到着は普通に起きる（C-6・D-11 と同じ結論で、制約はDBに置く）。
--
-- ## nullable にする理由
--
-- D-8 の経路（Bunshin 側のリダイレクタ `/go/{code}`）で入った行は
-- 識別子を持たない。PostgreSQL の UNIQUE は NULL を重複と見なさないので、
-- **既存行はいくつ NULL があっても通る。**

-- AlterTable
ALTER TABLE "link_clicks" ADD COLUMN     "event_id" TEXT;

-- CreateIndex
CREATE UNIQUE INDEX "link_clicks_event_id_key" ON "link_clicks"("event_id");
