-- リンク切れの状態（TASKS H-3b-schema、OPEN_QUESTIONS Q-029）。
--
-- ## なぜ保存するのか
--
-- H-3 は確かめて**その場で通知を積む**だけで、結果を残していない。
-- 通知の重複はジョブの冪等キー（ブログ・種類・JSTの日付）で防いでおり、
-- **通知の運用としてはそれで足りている。**
--
-- 足りないのは画面である。
--
-- 1. SPEC 6.1 の `/liff/blogs/[blogId]` は「エラー」を出すと定めているが、
--    **出す元になる状態がどこにも無い**
-- 2. **いつから切れているかが分からない。** 3日前からか今朝からかで、
--    モニターが直す優先度は変わる
--
-- ## なぜ2列なのか
--
-- **「確かめた時刻」と「切れ始めた時刻」は別物。**
--
-- - `link_checked_at` — 最後に確認した時刻。**通っていても入る。**
--   これが古ければ「確認できていない」であって「問題なし」ではない
-- - `link_broken_at` — **切れていると分かった最初の時刻。**
--   切れている間は**動かさない**（動かすと「いつからか」が毎回今日になる）。
--   直ったら `NULL` に戻す
--
-- 1列にまとめて「最後に切れていた時刻」にすると、**継続している切断と
-- 直った切断を区別できない。**
--
-- ## 一時的な失敗では切れたことにしない
--
-- H-3 が 404/410 だけを「消えた」とし、401/403/5xx を一時的な失敗として
-- 扱っているのと同じ扱いを、保存側でも守る（列はその判断を持たないので、
-- 書き込む側＝H-3b の責任）。
--
-- ## 既定値を入れない
--
-- 両方とも NULL のまま足す。`link_checked_at` に `now()` を入れると
-- **一度も確かめていない案件が「今日確認済み」になる**（D-13-schema と
-- 同じ判断）。`link_broken_at` に値を入れれば、切れていない案件が
-- 切れていることになる。

-- AlterTable
ALTER TABLE "affiliate_offers" ADD COLUMN     "link_broken_at" TIMESTAMPTZ(6),
ADD COLUMN     "link_checked_at" TIMESTAMPTZ(6);
